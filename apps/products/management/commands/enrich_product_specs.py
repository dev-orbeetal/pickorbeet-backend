class Command(BaseCommand):
    help = 'Replace incomplete product specification sets with fuller official specs.'

    def add_arguments(self, parser):
        parser.add_argument('--dry-run', action='store_true')

    @transaction.atomic
    def handle(self, *args, **options):
        dry_run = options['dry_run']
        updated = missing = 0
        for name, rows in REPLACE_SPECS_BY_NAME.items():
            product = Product.objects.filter(name=name).first()
            if product is None:
                missing += 1
                self.stdout.write(self.style.WARNING(f'Not found: {name}'))
                continue
            self.stdout.write(
                f'{"Would replace" if dry_run else "Replacing"} {name} '
                f'({product.specifications.count()} → {len(rows)} rows)'
            )
            if dry_run:
                updated += 1
                continue
            product.specifications.all().delete()
            for index, (spec_name, value) in enumerate(rows):
                ProductSpecification.objects.create(
                    product=product,
                    name=spec_name[:80],
                    value=value[:255],
                    sort_order=index,
                )
            updated += 1
        self.stdout.write(self.style.SUCCESS(
            f'Done. updated={updated} missing_products={missing} dry_run={dry_run}'
        ))
